package io.openaev.ocsf.schema.v1100.objects;

import io.openaev.ocsf.schema.OcsfObject;

@lombok.Getter
public class OcsfObjectDelegation extends OcsfObject {
  /**
   * The service or resource this delegation may be exercised against - the relying party that
   * should accept it, and that should reject it if presented anywhere else. When the delegation is
   * carried by an issued token, this is the audience the token names, typically a URI or service
   * identifier for the relying party. The issuer populates it at delegation time from the grant it
   * minted, so an issuer that scopes a delegation to a particular relying party already holds the
   * value; issuers that mint unscoped delegations omit it, which is why the attribute is optional.
   * Note this is the party the authority is <em>exercised on</em>, not the party that later reads
   * or audits the record - a delegation restricted to one payments API keeps that restriction on
   * record regardless of who consumes the event afterwards.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "audience")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeStringT audienceField;

  /** The time when the delegation was issued by the issuing authority. */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "created_time_dt")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeDatetimeT createdTimeDtField;

  /** The time when the delegation was issued by the issuing authority. */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "created_time")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeTimestampT createdTimeField;

  /**
   * The time when this delegation's granted authority expires. After this time the delegation no
   * longer conveys authority, independent of any revocation.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "expiration_time_dt")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeDatetimeT expirationTimeDtField;

  /**
   * The time when this delegation's granted authority expires. After this time the delegation no
   * longer conveys authority, independent of any revocation.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "expiration_time")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeTimestampT expirationTimeField;

  /**
   * The unique identifier of the trusted issuing authority (e.g., an OAuth authorization server,
   * cloud STS, IAM broker, orchestration gateway, or SDK wrapper) that generated this delegation.
   * Enables verification that delegation IDs were issued by an authorized component rather than
   * self-asserted by the delegate.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "issuer_uid")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeStringT issuerUidField;

  /**
   * The delegation identifier of the parent delegation, if this delegation was created by
   * re-delegating authority to another party (e.g., a downstream service or automated process).
   * This creates a parent-child relationship that enables tracking the complete chain of delegation
   * ancestry. Does not indicate that the delegate was instantiated or spawned by the parent's
   * delegate; that relationship, if any, is tracked separately.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "parent_uid")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeStringT parentUidField;

  /**
   * The authorization scopes granted at this delegation node, bounding what the delegate is
   * authorized to do on the principal's behalf (e.g., OAuth scope labels). Comparing a delegation's
   * scopes with its parent's scopes reveals scope attenuation across the chain.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "scopes")
  private java.util.List<io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeStringT> scopesField;

  /**
   * Unique identifier for this delegation context. Must be stable across the lifetime of the
   * delegation and generated by a trusted issuing authority (e.g., an OAuth authorization server,
   * cloud STS, IAM broker, or orchestration gateway) rather than self-asserted by the delegate. All
   * events executed under this delegation share this identifier.
   */
  @com.fasterxml.jackson.annotation.JsonProperty(value = "uid")
  private io.openaev.ocsf.schema.v1100.datatypes.OcsfDatatypeStringT uidField;
}
