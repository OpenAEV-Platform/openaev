// fds:keep-mui Alert: the library has no banner/alert component yet
import { Button, Chip, Paper, Tabs, TabsList, TabsTrigger, Text } from '@filigran/design-system';
import { Alert } from '@mui/material';
import { type ReactNode, useMemo, useState } from 'react';

import Empty from '../../../components/Empty';
import { useFormatter } from '../../../components/i18n';
import GenerateAiButton from './GenerateAiButton';
import GenerateDialog, { type GenerateDefaults } from './GenerateDialog';
import MitreMitigationList from './MitreMitigationList';
import RemediationMitigationItemCard from './RemediationMitigationItemCard';
import {
  type CollectorType,
  REMEDIATION_CONTROL_TYPES,
  type RemediationMitigationCategory,
} from './remediationMitigationMock';
import {
  generateItem,
  getItems,
  resetMockData,
  resolvePayload,
  unavailableKey,
  useMockStore,
  type Vendor,
  VENDORS,
  type Verdict,
} from './remediationMitigationStore';
import RemediationTypeSection from './RemediationTypeSection';
import useRemediationMitigationLabels from './useRemediationMitigationLabels';
import VendorLogo from './VendorLogo';
import { type RequestContext } from './xtmOneRequest';

const VENDOR_PREFIX = 'vendor:';

// The two tabs of a mitigation: what a security product can do (generated by XTM One), and what MITRE ATT&CK
// publishes for the techniques of the action (no product, nothing generated).
type MitigationMode = 'vendor' | 'generic';

// What the attack path step observed. Drives the smart hints.
export interface PanelContext {
  findingType?: string;
  verdicts?: {
    prevention?: Verdict;
    detection?: Verdict;
    vulnerability?: Verdict;
  };
}

interface Props {
  category: RemediationMitigationCategory;
  // Name of the payload (or inject) the tab is for. Resolved to a sample payload.
  payloadName?: string | null;
  // Review / edit / delete (Threat Arsenal and attack path). Atomic testing is read-mostly.
  editable?: boolean;
  context?: PanelContext;
  // Mitigation only: types of the findings the action produced, shown on the vendor-specific cards.
  findingTypes?: string[];
  // Remediation only: the hosts where the remediation must be applied.
  affectedHosts?: string[];
  // ATT&CK technique ids of the action. Defaults to the ones of the sample payload.
  techniques?: string[];
  // Mitigation only: which view to show. Set by the caller that owns the tabs; when it is not set the panel shows
  // its own Vendor-specific / Generic tabs.
  mitigationMode?: MitigationMode;
  // Lets a prevention item jump to the Remediation tab of the same payload.
  onSwitchToRemediation?: () => void;
}

const listStyle = {
  display: 'flex',
  flexDirection: 'column' as const,
  gap: 4,
  minWidth: 280,
  maxWidth: 320,
  flexShrink: 0,
};

// The content of the "Remediation" and "Mitigation" tabs: same layout, driven by the category.
// PROTOTYPE: sample data in memory, every "AI" action is simulated.
const RemediationMitigationPanel = ({
  category,
  payloadName,
  editable = false,
  context,
  findingTypes,
  affectedHosts,
  techniques,
  mitigationMode,
  onSwitchToRemediation,
}: Props) => {
  const { t } = useFormatter();
  const labels = useRemediationMitigationLabels();
  const store = useMockStore();
  const payload = useMemo(() => resolvePayload(payloadName), [payloadName]);
  const isMitigation = category === 'mitigation';
  const [ownMode, setMode] = useState<MitigationMode>('vendor');
  const mode = mitigationMode ?? ownMode;
  const [selected, setSelected] = useState<string | null>(null);
  const [dialog, setDialog] = useState<{
    open: boolean;
    defaults?: GenerateDefaults;
  }>({ open: false });

  const items = getItems(store, payload.id, category);

  // Only the SIEM / EDR products OpenAEV supports (a collector exists). Prevention and detection are not
  // separated: a vendor shows everything it can do, each card says which kind it is.
  const supportedVendors = VENDORS.filter(vendor => vendor.collector);
  const entries = supportedVendors.map(vendor => `${VENDOR_PREFIX}${vendor.collector}`);
  const current = selected && entries.includes(selected) ? selected : entries[0];

  // A CVE finding already has its fix in the platform: no new content is generated for it.
  const isCve = !isMitigation && context?.findingType === 'cve';

  const requestContext: RequestContext | undefined = context
    ? {
        findingType: context.findingType,
        verdict: (['prevention', 'detection', 'vulnerability'] as const)
          .flatMap(name => (context.verdicts?.[name]
            ? [{
                name,
                value: context.verdicts[name] as Verdict,
              }]
            : []))[0],
      }
    : undefined;

  // Vendor-specific mitigation: no dialog, the open vendor is the request. The vendor generates every kind of
  // control it can do (detection, and prevention when it can block), all shown together.
  const [generatingKey, setGeneratingKey] = useState<string | null>(null);
  const generateForVendor = (vendor: Vendor, collector: CollectorType) => {
    setGeneratingKey(collector);
    Promise.all(vendor.controls
      .filter((controlType): controlType is 'detection' | 'prevention' => controlType === 'detection' || controlType === 'prevention')
      .map(controlType => generateItem({
        payload,
        category,
        controlType,
        collector,
        findingType: context?.findingType,
      }))).finally(() => setGeneratingKey(null));
  };

  const openDialog = (defaults?: GenerateDefaults) => setDialog({
    open: true,
    defaults,
  });

  const hints: {
    key: string;
    text: string;
    defaults?: GenerateDefaults;
  }[] = [];
  if (isMitigation && context?.verdicts?.detection === 'not_met') {
    hints.push({
      key: 'detection',
      text: t('Detection = Not met'),
      defaults: { controlType: 'detection' },
    });
  }
  if (isMitigation && context?.verdicts?.prevention === 'not_met') {
    hints.push({
      key: 'prevention',
      text: t('Prevention = Not met'),
      defaults: {
        controlType: 'prevention',
        collector: 'crowdstrike',
      },
    });
  }
  if (!isMitigation && context?.verdicts?.vulnerability === 'met' && !isCve) {
    hints.push({
      key: 'vulnerability',
      text: t('Vulnerability = Met'),
    });
  }
  const hintLabel = (key: string) => {
    if (key === 'detection') return t('Generate detection mitigation');
    if (key === 'prevention') return t('Generate prevention mitigation');
    return t('Generate remediation');
  };

  const card = (item: (typeof items)[number]) => (
    <RemediationMitigationItemCard
      key={item.id}
      item={item}
      payload={payload}
      findingTypes={context?.findingType ? [context.findingType] : findingTypes}
      affectedHosts={affectedHosts}
      payloadId={payload.id}
      editable={editable}
      onSwitchToRemediation={onSwitchToRemediation}
    />
  );

  const emptyMessage = isMitigation
    ? t('No mitigation available for this action yet.')
    : t('No remediation available for this action yet.');

  // The pane of the selected entry: a Paper with its title and its Generate button in the top right corner.
  const pane = (title: ReactNode, action: ReactNode, body: ReactNode) => (
    <div style={{
      display: 'grid',
      gridTemplateColumns: 'minmax(0, 1fr)',
    }}
    >
      <Paper
        padding={16}
        title={title}
        action={action}
        style={{
          display: 'flex',
          flexDirection: 'column',
          gap: 12,
        }}
      >
        {body}
      </Paper>
    </div>
  );

  // Vendor-specific mitigation: detection and prevention together, one pane per vendor.
  const renderVendorBody = () => {
    const collector = current.slice(VENDOR_PREFIX.length) as CollectorType;
    const vendor = VENDORS.find(entry => entry.collector === collector);
    if (!vendor) return null;
    const visible = items
      .filter(item => item.collector_type === collector)
      .sort((a, b) => a.control_type.localeCompare(b.control_type));
    // XTM One answered that it has no suggestion for this request: say so, with its reason.
    const reasons = vendor.controls.flatMap((controlType) => {
      const reason = store.unavailable[unavailableKey(payload.id, 'mitigation', controlType, collector)];
      return reason ? [`${labels.controlType[controlType]} ${labels.category.mitigation.toLowerCase()}: ${t('XTM One has no suggestion for this request.')} ${reason}`] : [];
    });
    return pane(
      <span style={{
        display: 'inline-flex',
        alignItems: 'center',
        gap: 8,
      }}
      >
        <VendorLogo vendorId={vendor.id} label={vendor.label} size={22} />
        {`${vendor.label} (${vendor.kind})`}
      </span>,
      <GenerateAiButton disabled={!!generatingKey} onClick={() => generateForVendor(vendor, collector)}>
        {generatingKey === collector ? t('Generating…') : t('Generate mitigation')}
      </GenerateAiButton>,
      <>
        {visible.length === 0 && <Empty message={reasons.length > 0 ? reasons.join(' ') : emptyMessage} />}
        {visible.map(card)}
        {visible.length > 0 && reasons.length > 0 && reasons.map(reason => (
          <Text key={reason} variant="content-caption" className="text-default-secondary">{reason}</Text>
        ))}
      </>,
    );
  };

  // Remediation without assets (Threat Arsenal, attack path): one pane, Generate in its top right corner.
  const renderRemediationBody = () => {
    const reason = store.unavailable[unavailableKey(payload.id, 'remediation')];
    return pane(
      t('Remediation'),
      <GenerateAiButton disabled={isCve} onClick={() => openDialog()}>
        {t('Generate remediation')}
      </GenerateAiButton>,
      // One section per control type; a type without any suggestion says so.
      REMEDIATION_CONTROL_TYPES.map((controlType) => {
        const ofType = items.filter(item => item.control_type === controlType);
        const title = `${labels.controlType[controlType]} ${labels.category.remediation.toLowerCase()}`;
        return (
          <RemediationTypeSection
            key={controlType}
            title={title}
            hasItems={ofType.length > 0}
            emptyText={`${t('No suggestion available.')}${reason ? ` ${t('XTM One has no suggestion for this request.')} ${reason}` : ''}`}
          >
            {ofType.map(card)}
          </RemediationTypeSection>
        );
      }),
    );
  };

  return (
    <div style={{
      display: 'flex',
      flexDirection: 'column',
      gap: 12,
    }}
    >
      {isCve && (
        <Alert severity="info" variant="outlined">
          {t('Vulnerability record remediation: the fix for this CVE already exists in the vulnerability record of the platform, so nothing new is generated here. (Sample text.)')}
        </Alert>
      )}

      {(!isMitigation || mode === 'vendor') && hints.map(hint => (
        <Alert
          key={hint.key}
          severity="warning"
          variant="outlined"
          action={<Button size="sm" variant="ia" onClick={() => openDialog(hint.defaults)}>{hintLabel(hint.key)}</Button>}
        >
          {`${hint.text}. ${t('Suggested next step')}: ${hintLabel(hint.key)}.`}
        </Alert>
      ))}

      {isMitigation && !mitigationMode && (
        <Tabs value={mode} onValueChange={value => setMode(value as MitigationMode)} panels="external">
          <TabsList aria-label={t('Mitigation type')}>
            <TabsTrigger value="vendor">{t('Vendor-specific')}</TabsTrigger>
            <TabsTrigger value="generic">{t('Generic')}</TabsTrigger>
          </TabsList>
        </Tabs>
      )}

      {isMitigation && mode === 'generic' && <MitreMitigationList techniques={techniques ?? payload.attack_techniques} />}

      {isMitigation && mode === 'vendor' && (
        <div style={{
          display: 'flex',
          gap: 16,
          alignItems: 'flex-start',
        }}
        >
          <div style={listStyle}>
            {/* Same rail as the security platforms of the main Remediation tab: vertical library tabs, logo + name. */}
            <Tabs
              orientation="vertical"
              value={current}
              onValueChange={setSelected}
              panels="external"
              style={{ display: 'grid' }}
            >
              <TabsList aria-label={t('Vendor-specific')}>
                {supportedVendors.map(vendor => (
                  <TabsTrigger
                    key={vendor.id}
                    value={`${VENDOR_PREFIX}${vendor.collector}`}
                    icon={<VendorLogo vendorId={vendor.id} label={vendor.label} />}
                  >
                    {`${vendor.label} (${vendor.kind})`}
                  </TabsTrigger>
                ))}
              </TabsList>
            </Tabs>
          </div>
          <div style={{
            flex: 1,
            minWidth: 0,
          }}
          >
            {renderVendorBody()}
          </div>
        </div>
      )}

      {!isMitigation && (
        <div style={{
          display: 'flex',
          flexDirection: 'column',
          gap: 12,
        }}
        >
          {renderRemediationBody()}
        </div>
      )}

      <div style={{
        display: 'flex',
        alignItems: 'center',
        gap: 8,
      }}
      >
        <Chip label={t('SAMPLE DATA - prototype, nothing is stored or sent')} severity="medium" />
        <Button size="sm" priority="tertiary" onClick={resetMockData}>{t('Reset mock data')}</Button>
      </div>

      <GenerateDialog
        open={dialog.open}
        onClose={() => setDialog({ open: false })}
        payload={payload}
        category={category}
        context={requestContext}
        defaults={dialog.defaults}
      />
    </div>
  );
};

export default RemediationMitigationPanel;
