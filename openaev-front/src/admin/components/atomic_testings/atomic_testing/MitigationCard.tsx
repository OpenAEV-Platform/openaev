import { Button, Chip, type ChipSeverity, Paper, Text } from '@filigran/design-system';
import { SvgIcon } from '@mui/material';
import { LogoXtmOneIcon } from 'filigran-icon';

import { useFormatter } from '../../../../components/i18n';
import { tint } from '../../../../utils/tint';

// PROTOTYPE: shared by the atomic testing / simulation inject "Mitigations" tab and by the attack
// path execution panel. Renders one mitigation suggestion, no data fetching.

export type Criticality = 'low' | 'medium' | 'high' | 'critical';

// A finding a mitigation is for. The value is only present for non-sensitive types (share name,
// port, service...); for sensitive types (credentials, hash) only the type exists, the value is
// masked and never leaves the platform.
export interface MitigationFinding {
  type: string;
  value?: string;
}

export interface MockMitigation {
  // How urgent it is to close the weakness. Returned by XTM One and displayed as is (never computed here).
  criticality: Criticality;
  // The findings (and so the weakness) this mitigation is for.
  addresses: MitigationFinding[];
  summary: string;
  steps: {
    text: string;
    command?: string;
  }[];
  risk: 'low' | 'medium' | 'high';
  impact: string;
  rollback: string;
  limitedContext: boolean;
}

export const criticalitySeverity: Record<Criticality, ChipSeverity> = {
  low: 'low',
  medium: 'medium',
  high: 'high',
  critical: 'critical',
};

const riskSeverity: Record<MockMitigation['risk'], ChipSeverity> = {
  low: 'low',
  medium: 'medium',
  high: 'high',
};

interface Props {
  mitigation: MockMitigation;
  // Name of the agent/execution the suggestion was first generated for, when it is reused.
  reusedFrom?: string;
  onRegenerate: () => void;
}

const MitigationCard = ({ mitigation, reusedFrom, onRegenerate }: Props) => {
  const { t } = useFormatter();

  return (
    <Paper
      padding={16}
      style={{
        display: 'flex',
        flexDirection: 'column',
        gap: 16,
      }}
    >
      <div style={{
        display: 'flex',
        alignItems: 'center',
        gap: 8,
        flexWrap: 'wrap',
      }}
      >
        <Chip
          startIcon={<SvgIcon component={LogoXtmOneIcon} fontSize="small" inheritViewBox />}
          label={t('Mitigation generated by AI')}
          severity="info"
        />
        <Chip label={`${t('Criticality')}: ${t(mitigation.criticality)}`} severity={criticalitySeverity[mitigation.criticality]} />
        <Chip label={`${t('Risk of applying')}: ${t(mitigation.risk)}`} severity={riskSeverity[mitigation.risk]} />
        {mitigation.limitedContext && <Chip label={t('Limited context')} severity="medium" />}
        {reusedFrom && <Chip label={`${t('Reused from')} ${reusedFrom}`} severity="neutral" />}
        <div style={{ marginLeft: 'auto' }}>
          <Button priority="secondary" onClick={onRegenerate}>
            {t('Regenerate')}
          </Button>
        </div>
      </div>

      <Text variant="content-compact">{mitigation.summary}</Text>

      {mitigation.addresses.length > 0 && (
        <div>
          <Text variant="content-base-bold" className="mb-1 block text-default-secondary">
            {t('Affected findings')}
          </Text>
          <div style={{
            display: 'flex',
            flexWrap: 'wrap',
            gap: 6,
          }}
          >
            {mitigation.addresses.map(finding => (
              <Chip
                key={`${finding.type}-${finding.value ?? ''}`}
                label={finding.value ? `${finding.type}: ${finding.value}` : `${finding.type} (${t('value masked')})`}
                severity="neutral"
              />
            ))}
          </div>
        </div>
      )}

      <div>
        <Text variant="content-base-bold" className="mb-2 block text-default-secondary">
          {t('Steps')}
        </Text>
        <ol style={{
          margin: 0,
          paddingLeft: 20,
          display: 'flex',
          flexDirection: 'column',
          gap: 12,
        }}
        >
          {mitigation.steps.map(step => (
            <li key={step.text}>
              <Text variant="content-compact">{step.text}</Text>
              {step.command && (
                <div
                  style={{
                    marginTop: 4,
                    fontFamily: '"IBM Plex Mono", "Roboto Mono", monospace',
                    fontSize: 12.5,
                    backgroundColor: tint('currentColor', 6),
                    borderRadius: 4,
                    padding: 8,
                    overflowX: 'auto',
                    whiteSpace: 'pre-wrap',
                    wordBreak: 'break-word',
                  }}
                >
                  {step.command}
                </div>
              )}
            </li>
          ))}
        </ol>
      </div>

      <div style={{
        display: 'grid',
        gridTemplateColumns: 'repeat(auto-fit, minmax(240px, 1fr))',
        gap: 16,
      }}
      >
        <div>
          <Text variant="content-base-bold" className="block text-default-secondary">{t('Impact')}</Text>
          <Text variant="content-compact">{mitigation.impact}</Text>
        </div>
        <div>
          <Text variant="content-base-bold" className="block text-default-secondary">{t('Rollback')}</Text>
          <Text variant="content-compact">{mitigation.rollback}</Text>
        </div>
      </div>
    </Paper>
  );
};

export default MitigationCard;
